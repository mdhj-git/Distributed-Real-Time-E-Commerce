<?php

namespace Modules\Products\Contracts;

use Modules\Products\Contracts\DTOs\StockItem;
use Modules\Products\Contracts\Exceptions\InsufficientStockException;
use Modules\Products\Contracts\Exceptions\InventoryUnavailableException;

/**
 * Every method is atomic on its own and never relies on the caller's transaction.
 * Implementations are swapped by one binding line in ProductsServiceProvider
 * (local now, gRPC in Requirement 2).
 */
interface InventoryService
{
    /**
     * Returns the current quantity of each product. A product with no stock
     * record has quantity 0. An empty input returns an empty array. Duplicate
     * ids are allowed.
     *
     * @param  array<int, int>  $productIds
     * @return array<int, int> Quantities keyed by product id.
     *
     * @throws InventoryUnavailableException
     */
    public function getStock(array $productIds): array;

    /**
     * Reserves all items or none of them, atomically on its own.
     *
     * On shortage it throws InsufficientStockException whose details are exactly:
     * {"shortages": [{"product_id": int, "requested": int, "available": int}, ...]}
     * with one entry per short product.
     *
     * The remote implementation is idempotent by $reference. The local
     * implementation is not, so callers must never call reserve twice with
     * the same $reference.
     *
     * @param  string  $reference  Unique id per order (UUID string), generated by the caller.
     * @param  array<int, StockItem>  $items
     *
     * @throws InsufficientStockException
     * @throws InventoryUnavailableException
     */
    public function reserve(string $reference, array $items): void;

    /**
     * Gives back the quantities in $items that were reserved under $reference.
     *
     * The local implementation uses $items. The remote implementation may ignore
     * $items because the inventory service remembers what it reserved under
     * $reference.
     *
     * The local implementation is not idempotent: callers (Orders) protect it
     * with the order row lock and the order status check. The remote
     * implementation is idempotent by $reference.
     *
     * @param  string  $reference  The same reference that was passed to reserve.
     * @param  array<int, StockItem>  $items
     *
     * @throws InventoryUnavailableException
     */
    public function release(string $reference, array $items): void;

    /**
     * Changes the quantity by $delta (positive or negative, never 0) and returns
     * the new quantity. Throws InsufficientStockException if the result would
     * be negative.
     *
     * @return int The new quantity.
     *
     * @throws InsufficientStockException
     * @throws InventoryUnavailableException
     */
    public function adjust(int $productId, int $delta): int;
}
